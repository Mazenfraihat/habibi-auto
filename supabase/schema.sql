-- ── ADMINS ──
-- Only users listed here can change inventory or read contact messages.
-- Add yourself after creating your user in Authentication → Users:
--   insert into public.admin_users (user_id)
--   select id from auth.users where email = 'you@example.com';
create table if not exists public.admin_users (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
-- No policies: the table is only read through is_admin() below.

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;
grant execute on function public.is_admin() to anon, authenticated;

-- ── CARS ──
create table if not exists public.cars (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  make        text   not null,
  year        text   not null,
  name        text   not null,
  price       text   not null,             -- preformatted, e.g. '15,500' (no "$")
  badge       text   not null default '',
  badge_type  text   not null default 'hot' check (badge_type in ('hot', 'perf')),
  specs       jsonb  not null default '[]', -- [{ "label": "Mileage", "value": "17,400 mi" }, …]
  highlights  text[] not null default '{}',
  photo_url   text   not null,             -- public URL, or a relative path for bundled images
  photo_path  text                         -- object path in the car-photos bucket (null for bundled images)
);
alter table public.cars enable row level security;

drop policy if exists "Anyone can read cars" on public.cars;
create policy "Anyone can read cars" on public.cars
  for select to anon, authenticated using (true);

drop policy if exists "Admins can insert cars" on public.cars;
create policy "Admins can insert cars" on public.cars
  for insert to authenticated with check (public.is_admin());

drop policy if exists "Admins can update cars" on public.cars;
create policy "Admins can update cars" on public.cars
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Admins can delete cars" on public.cars;
create policy "Admins can delete cars" on public.cars
  for delete to authenticated using (public.is_admin());

-- ── CONTACT MESSAGES ──
create table if not exists public.contact_messages (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  name         text not null check (char_length(name) between 1 and 200),
  phone        text check (char_length(phone) <= 50),
  car_interest text check (char_length(car_interest) <= 300),
  message      text check (char_length(message) <= 5000)
);
alter table public.contact_messages enable row level security;

drop policy if exists "Anyone can send a message" on public.contact_messages;
create policy "Anyone can send a message" on public.contact_messages
  for insert to anon, authenticated with check (true);

drop policy if exists "Admins can read messages" on public.contact_messages;
create policy "Admins can read messages" on public.contact_messages
  for select to authenticated using (public.is_admin());

drop policy if exists "Admins can delete messages" on public.contact_messages;
create policy "Admins can delete messages" on public.contact_messages
  for delete to authenticated using (public.is_admin());

-- ── PHOTO STORAGE ──
insert into storage.buckets (id, name, public)
values ('car-photos', 'car-photos', true)
on conflict (id) do nothing;

drop policy if exists "Admins can read car photos" on storage.objects;
create policy "Admins can read car photos" on storage.objects
  for select to authenticated using (bucket_id = 'car-photos' and public.is_admin());

drop policy if exists "Admins can upload car photos" on storage.objects;
create policy "Admins can upload car photos" on storage.objects
  for insert to authenticated with check (bucket_id = 'car-photos' and public.is_admin());

drop policy if exists "Admins can delete car photos" on storage.objects;
create policy "Admins can delete car photos" on storage.objects
  for delete to authenticated using (bucket_id = 'car-photos' and public.is_admin());

